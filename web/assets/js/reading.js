  /* ───────────────── 나와 맞는 일주 · 조심할 일주 ───────────────── */
  function matches(rec, opts) {
    opts = opts || {};
    if (!ONM.compat || !ONM.ILJU) return null;
    var list = [];
    Object.keys(ONM.ILJU).forEach(function (id) {
      var other = ONM.ILJU[id];
      if (!other || !other.stemInfo || id === rec.id) return;
      var cp = ONM.compat.compare(rec, other);
      list.push({
        id: id, score: cp.score, grade: cp.grade,
        phrase: ONM.iljuPhrase ? ONM.iljuPhrase(other) : id,
        why: (cp.good && cp.good[0]) || cp.headline,
        care: (cp.care && cp.care[0]) || cp.headline
      });
    });
    list.sort(function (x, y) { return y.score - x.score || (x.id < y.id ? -1 : 1); });
    var n = opts.limit || 4;
    return {
      best: list.slice(0, n),
      careful: list.slice(-2).reverse().map(function (x) { return { id: x.id, score: x.score, phrase: x.phrase, why: x.care }; })
    };
  }

