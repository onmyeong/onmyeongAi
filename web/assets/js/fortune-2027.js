  function jong(word) {
    var s = String(word);
    for (var k = s.length - 1; k >= 0; k--) {
      var ch = s.charCodeAt(k);
      if (ch >= 0xac00 && ch <= 0xd7a3) return (ch - 0xac00) % 28;
    }
    return 0;
  }
